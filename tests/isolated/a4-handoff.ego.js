const FX = 'http://127.0.0.1:' + ((typeof process !== 'undefined' && process.env.TP_FIXTURE_PORT) || 8899) + '/';
// RG-A4: handOff must pause agent page actions; waitForControl must really wait.
const ok = (n, c, x = '') => { console.log(`${c ? 'PASS' : 'FAIL'} A4 ${n}${x ? ' — ' + x : ''}`); if (!c) process.exitCode = 1; };
const err = async (f) => { try { await f(); return null; } catch (e) { return e; } };
const t = await taskSpace('rg-a4');
const p = t.page('p1');
await p.goto(FX, { waitUntil: 'load' });
await t.handOff();
let e = await err(() => p.goto(FX + '?x'));
ok('goto refused while handed off', e && e.name === 'HandedOffError', e ? e.name : 'no error');
e = await err(() => p.snapshot());
ok('snapshot refused while handed off', e && e.name === 'HandedOffError', e ? e.name : 'no error');
e = await err(() => p.click('text=問候'));
ok('click refused while handed off', e && e.name === 'HandedOffError', e ? e.name : 'no error');
e = await err(() => t.cdp('Target.attachToTarget', { targetId: p.targetId, flatten: true }));
ok('raw cdp attach refused while handed off', e && e.name === 'HandedOffError', e ? e.name : 'no error');
const other = await taskSpace('rg-a4-other');
e = await err(() => other.cdp('Runtime.evaluate', { expression: '1' }));
ok('raw cdp from another space refused while one is handed off', e && e.name === 'HandedOffError', e ? e.name : 'no error');
e = await err(() => t.cdp('Target.getTargets', {}));
ok('Target.getTargets refused while handed off (tab URLs may hold secrets)', e && e.name === 'HandedOffError', e ? e.name : 'no error');
ok('Browser.getVersion still allowed', (await t.cdp('Browser.getVersion', {})).product !== undefined);
await other.finish();
ok('url still readable', (await p.url()).startsWith(FX));
const again = await taskSpace(t.spaceId);
e = await err(() => again.page('p1').goto(FX + '?y'));
ok('re-opening the space does not steal control', e && e.name === 'HandedOffError', e ? e.name : 'no error');
const t0 = Date.now();
e = await err(() => t.waitForControl({ timeout: 1500 }));
ok('waitForControl waits then times out', e && e.name === 'TimeoutError' && Date.now() - t0 >= 1400, `${Date.now() - t0}ms`);
const w = t.waitForControl({ timeout: 10000 });
setTimeout(() => { t.takeOver().catch(() => {}); }, 1000);
const t1 = Date.now();
const r = await w;
ok('waitForControl resolves after control returns', r.control === true && Date.now() - t1 >= 800, `${Date.now() - t1}ms`);
await p.goto(FX + '?z', { waitUntil: 'load' });
ok('goto works again after takeOver', (await p.url()).includes('?z'));
ok('raw cdp works after takeOver', (await t.cdp('Browser.getVersion', {})).product !== undefined);
e = await err(() => t.cdp('Target.getBrowserContexts', {}));
ok('non-allowlisted raw cdp allowed after takeOver', e === null, e ? `${e.name} ${e.message}` : '');
const t2 = await taskSpace('rg-a4-del');
await t2.handOff();
const wd = t2.waitForControl({ timeout: 20000 });
setTimeout(() => { t2.finish().catch(() => {}); }, 500);
const t3 = Date.now();
e = await err(() => wd);
ok('waitForControl stops when space is deleted', e && e.name === 'UnknownSpace' && Date.now() - t3 < 5000, `${e ? e.name : 'resolved'} ${Date.now() - t3}ms`);
await t.finish();
