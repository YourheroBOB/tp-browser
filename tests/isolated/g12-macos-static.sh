#!/bin/sh
# G12 / RG-A12: static checks for paths macOS (Darwin) actually runs.
# Does not start a browser, does not bind a port, does not read a real profile.
# GNU-only flags must not appear on those paths. /proc reads must be behind a
# test that fails closed when /proc is absent. Shell syntax is checked with
# both sh -n and bash -n (macOS /bin/sh is bash 3.2 in POSIX mode; login shell is zsh).
set -eu
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
fail=0
ok() { echo "PASS G12 $*"; }
bad() { echo "FAIL G12 $*"; fail=1; }

SHELLS="scripts/tp-start.sh scripts/tp-stop.sh scripts/tp-ps.sh install.sh"
JS="bin/ego-browser.js bin/tp-browser.js tools/profile-init.js lib/sdk.js daemon/cdp.js daemon/ego-browserd.js daemon/flush-and-close.js daemon/inpage.agent.js daemon/keys.js daemon/page-ops.js daemon/store.js daemon/tp-browserd.js"

if command -v bash >/dev/null 2>&1; then
  :
else
  bad "bash is required for bash -n"
fi

for f in $SHELLS; do
  if sh -n "$f" && bash -n "$f"; then ok "syntax $f"; else bad "syntax $f"; fi
done
if sh -n "$0" && bash -n "$0"; then ok "syntax $0"; else bad "syntax $0"; fi

# Generated by install.sh; not a source file. Same two-liner must parse on Darwin.
if grep -q 'exec "$HOME/.local/share/ego-linux/app/scripts/tp-start.sh" --headed "$@"' install.sh; then
  tmp="$(mktemp /tmp/tp-g12-headed.XXXXXX)"
  printf '%s\n' '#!/bin/sh' 'exec "$HOME/.local/share/ego-linux/app/scripts/tp-start.sh" --headed "$@"' > "$tmp"
  if sh -n "$tmp" && bash -n "$tmp"; then ok "syntax tp-headed.sh wrapper"; else bad "syntax tp-headed.sh wrapper"; fi
  rm -f "$tmp"
else
  bad "install.sh does not write the tp-headed wrapper"
fi

if [ -f uninstall.sh ]; then
  if sh -n uninstall.sh && bash -n uninstall.sh; then ok "syntax uninstall.sh"; else bad "syntax uninstall.sh"; fi
else
  ok "no uninstall.sh"
fi

# Comment lines are ignored. A hit is a command Darwin would execute.
gnu_hits() {
  grep -nE "$2" "$1" 2>/dev/null | grep -vE '(^|:)[0-9]+:[[:space:]]*#' || true
}
for f in $SHELLS; do
  h="$(gnu_hits "$f" 'sed[[:space:]]+-i|readlink[[:space:]]+-[fem]|date[[:space:]]+-d|date[[:space:]]+--date|grep[[:space:]]+-P|stat[[:space:]]+-c|stat[[:space:]]+--format|pgrep[[:space:]]|mktemp[[:space:]].*--suffix|ps[[:space:]]+--no-headers|(^|[;&|`(])[[:space:]]*timeout[[:space:]]')"
  if [ -n "$h" ]; then echo "$h"; bad "GNU-only or nonportable command in $f"; else ok "no GNU-only flags in $f"; fi
  h="$(gnu_hits "$f" '/proc/')"
  badproc=""
  if [ -n "$h" ]; then
    # Safe when the line itself tests -r/-f, or it is the body directly under that test
    # (macOS has no /proc, so the body is not taken).
    badproc="$(printf '%s\n' "$h" | awk '
      {
        line=$0
        sub(/^[^:]*:[0-9]*:/, "", line)
        if (line ~ /\[/ && (line ~ /-r/ || line ~ /-f/) && line ~ /\/proc\//) { prev="guard"; next }
        if (prev=="guard") { prev=""; next }
        print
        bad=1
      }
      END { exit 0 }
    ')"
  fi
  if [ -n "$badproc" ]; then echo "$badproc"; bad "unguarded /proc in $f"; else ok "/proc guarded in $f"; fi
  h="$(grep -nE '(^|[[:space:]])ps[[:space:]]' "$f" | grep -vE '(^|:)[0-9]+:[[:space:]]*#' | grep -v 'ww' || true)"
  if [ -n "$h" ]; then echo "$h"; bad "ps without -ww in $f"; else ok "ps uses -ww in $f"; fi
done

for f in $JS; do
  if node --check "$f"; then ok "node --check $f"; else bad "node --check $f"; fi
done

# /proc in the daemon may only live in the Linux listener, or in describeChrome after the linux check.
if awk '
  /^function findListenerPid/ { zone="procfn" }
  /^function describeChrome/ { zone="describe"; linux=0 }
  /^function / && !/^function findListenerPid/ && !/^function describeChrome/ { zone=""; linux=0 }
  /process\.platform === .linux./ { if (zone=="describe") linux=1 }
  /process\.platform === .darwin./ { linux=0 }
  /\/proc\// {
    if ($0 ~ /^[[:space:]]*\/\//) next
    if (zone=="procfn") next
    if (zone=="describe" && linux) next
    print FILENAME ":" NR ":" $0
    bad=1
  }
  END { exit bad }
' daemon/ego-browserd.js; then
  ok "/proc in ego-browserd.js is linux-only"
else
  bad "/proc in ego-browserd.js is reachable on darwin"
fi

grep -q "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" scripts/tp-start.sh \
  && ok "darwin Chrome.app path" || bad "missing Chrome.app path"
grep -q 'MAC_FLAGS="--use-mock-keychain"' scripts/tp-start.sh \
  && ok "darwin mock keychain flag" || bad "missing --use-mock-keychain"
n="$(grep -c 'MAC_FLAGS="--use-mock-keychain"' scripts/tp-start.sh || true)"
[ "$n" = "1" ] && ok "mock keychain assigned once" || bad "MAC_FLAGS assignment count=$n"
grep -q 'darwinChromeOnPort' daemon/ego-browserd.js && grep -q -- '-axww' daemon/ego-browserd.js \
  && ok "darwin chrome identity uses ps -axww" || bad "darwin chrome identity missing"
grep -q "join(appSup, 'Google', 'Chrome')" tools/profile-init.js \
  && grep -q "join(appSup, 'Google', 'Chrome Canary')" tools/profile-init.js \
  && ok "darwin Chrome profile roots" || bad "darwin Chrome profile roots"
grep -q "const dstCookiesDir = join(profileDef, 'Network')" tools/profile-init.js \
  && ok "cookies go to Default/Network" || bad "cookies dest is not Default/Network"
if grep -q "win32' ? join(profileDef, 'Network')" tools/profile-init.js; then
  bad "cookies dest still windows-only"
else
  ok "cookies dest not windows-only"
fi
grep -q '.zprofile' install.sh && grep -q 'uname -s' install.sh \
  && ok "installer has a Darwin PATH fallback" || bad "installer PATH fallback missing"
grep -q 'tp-ps.sh' scripts/tp-start.sh && grep -q 'tp-ps.sh' scripts/tp-stop.sh \
  && ok "start/stop source tp-ps.sh" || bad "start/stop do not source tp-ps.sh"

# Symlink install path: ~/.local/bin/tp-stop -> scripts/tp-stop.sh must still find tp-ps.sh.
# Do not execute tp-stop (it would curl a port).
linkdir="$(mktemp -d /tmp/tp-g12-link.XXXXXX)"
ln -s "$ROOT/scripts/tp-stop.sh" "$linkdir/tp-stop"
_tp_self="$linkdir/tp-stop"
_tp_n=0
while [ -L "$_tp_self" ] && [ "$_tp_n" -lt 8 ]; do
  _tp_n=$((_tp_n + 1))
  _tp_base="$(cd "$(dirname "$_tp_self")" && pwd)"
  _tp_target="$(readlink "$_tp_self" 2>/dev/null || true)"
  [ -n "$_tp_target" ] || break
  case "$_tp_target" in
    /*) _tp_self="$_tp_target" ;;
    *) _tp_self="$_tp_base/$_tp_target" ;;
  esac
done
if [ -f "$(cd "$(dirname "$_tp_self")" && pwd)/tp-ps.sh" ]; then ok "symlink resolves to tp-ps.sh"; else bad "symlink did not find tp-ps.sh"; fi
rm -rf "$linkdir"

# Exact --user-data-dir match on this host's ps (same -axww shape Darwin uses). Our processes only.
P="/tmp/tp-g12-profile.agent"
EXTRA="" DOT="" DECOY="" HLESS="" HELP="" HEAD=""
node -e 'setTimeout(()=>{},60000)' -- --headless=new --user-data-dir="$P" >/dev/null 2>&1 & HLESS=$!
node -e 'setTimeout(()=>{},60000)' -- --user-data-dir="${P}-EXTRA" >/dev/null 2>&1 & EXTRA=$!
node -e 'setTimeout(()=>{},60000)' -- --user-data-dir="/tmp/tp-g12-profileXagent" >/dev/null 2>&1 & DOT=$!
node -e 'setTimeout(()=>{},60000)' -- "$P" ego-browserd.js tp-browserd.js >/dev/null 2>&1 & DECOY=$!
node -e 'setTimeout(()=>{},60000)' -- --type=renderer --user-data-dir="$P" >/dev/null 2>&1 & HELP=$!
cleanup() {
  for p in ${HLESS:-} ${EXTRA:-} ${DOT:-} ${DECOY:-} ${HELP:-} ${HEAD:-}; do
    [ -n "$p" ] || continue
    kill "$p" 2>/dev/null || true
  done
}
trap cleanup EXIT INT TERM
sleep 0.4
PROFILE_DIR="$P"
# shellcheck disable=SC1091
. "$ROOT/scripts/tp-ps.sh"
got="$(tp_profile_pids)"
case " $got " in *" $HLESS "*) ok "exact pid matched" ;; *) bad "exact pid missed ($got)" ;; esac
case " $got " in *" $EXTRA "*) bad "prefix path matched" ;; *) ok "prefix path excluded" ;; esac
case " $got " in *" $DOT "*) bad "dot matched as wildcard" ;; *) ok "dot matched literally" ;; esac
case " $got " in *" $DECOY "*) bad "decoy with daemon name matched" ;; *) ok "decoy excluded" ;; esac
case " $got " in *" $HELP "*) ok "helper with exact flag listed" ;; *) bad "helper missed" ;; esac
if tp_profile_is_headed; then bad "headless main counted as headed"; else ok "headless main is not headed"; fi
node -e 'setTimeout(()=>{},60000)' -- --user-data-dir="$P" --window-size=1440,900 >/dev/null 2>&1 & HEAD=$!
sleep 0.3
if tp_profile_is_headed; then ok "headed main detected"; else bad "headed main not detected"; fi

echo "G12_RC=$fail"
exit "$fail"
